"""The optional signed anchor: an OpenSSH (SSHSIG) signature over a statement of run id, manifest digest and plan digest, kept outside the bundle and checked by ``verify`` with ONE public
key the verifying person supplies.

Every key in this file is a throwaway Ed25519 (or, where a test needs a refused type, RSA/ECDSA) key generated by the test with the real ``ssh-keygen`` into ``tmp_path`` (0600), never
committed, never reused, never printed beyond what the tests compare. No key of the machine the tests run on is read. ``ssh-keygen`` and ``ssh-agent`` are required: if they are missing
the tests FAIL (they never skip).

The tests that matter most: ``test_a_bundle_rewritten_and_re_chained_after_signing_...`` (the attack the feature exists for: plain ``verify`` accepts the rewritten bundle, the signature does
not) and the namespace/key/statement refusals. The mutations that prove each guard is load-bearing are in ``test_qr_mutations.py``."""
