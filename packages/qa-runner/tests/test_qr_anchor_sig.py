def test_a_hand_written_statement_is_not_the_statement(tmp_path, none_files):
    path = archive(tmp_path, none_files)
    priv, pub = keygen(tmp_path, "op")
    good = statement_for(none_files)
    variants = {"extra-whitespace": good + b"\n", "no-newline": good.rstrip(b"\n"), "compact": json.dumps(json.loads(good), sort_keys=True, separators=(",", ":")).encode(),
                "just-the-digest": manifest_digest(none_files).encode()}
    for name, statement in variants.items():
        code, doc, _ = verify_json(path, "--anchor-sig", sign_like_an_operator(priv, statement, tmp_path, name=name), "--anchor-pub", pub)
        assert code == K.EXIT_REJECTED and doc["anchor_signature"]["state"] == "invalid", name


def test_a_signature_made_for_another_run_or_plan_does_not_verify_for_this_bundle(tmp_path, none_files):
    """The same manifest digest, with another run id or another plan digest in the statement (a replayed signature): the run id and the plan digest are part of what is signed."""
    path = archive(tmp_path, none_files)
    priv, pub = keygen(tmp_path, "op")
    r = load(none_files, "report.json")
    md = manifest_digest(none_files)
    for name, args in (("other-run", ("r0-another-run", md, r["plan_digest"])), ("other-plan", (r["run_id"], md, "sha256:" + "5" * 64))):
        code, doc, _ = verify_json(path, "--anchor-sig", sign_like_an_operator(priv, A.statement_bytes(*args), tmp_path, name=name), "--anchor-pub", pub)
        assert code == K.EXIT_REJECTED and doc["anchor_signature"]["state"] == "invalid", name
    code, doc, _ = verify_json(path, "--anchor-sig", sign_like_an_operator(priv, A.statement_bytes(r["run_id"], md, r["plan_digest"]), tmp_path, name="own"), "--anchor-pub", pub)
    assert code == 0 and doc["anchor_signature"]["state"] == "verified"


