def test_the_openssh_client_the_signed_anchor_needs_is_present_and_has_the_signature_mode(tmp_path):
    """Fails (never skips) where ``ssh-keygen`` or ``ssh-agent`` is missing or too old: the version is recorded in the failure message and by the CI step that prints ``ssh -V``."""
    version = ssh("ssh", "-V", check=False)
    text = (version.stderr + version.stdout).decode(errors="replace").strip()
    assert shutil.which("ssh-keygen") and shutil.which("ssh-agent"), "ssh-keygen and ssh-agent are required by these tests: " + text
    assert A.tool_path() is not None, f"{A.TOOL_NAME} is not on {A.TOOL_SEARCH_PATH}: " + text
    priv, pub = keygen(tmp_path, "probe")
    sig = sign_like_an_operator(priv, b"probe", tmp_path)
    allowed = tmp_path / "allowed"
    allowed.write_text(A.parse_public_key(pub.read_bytes()).allowed_signers_line())
    ok = ssh("ssh-keygen", "-Y", "verify", "-f", str(allowed), "-I", A.PRINCIPAL, "-n", A.NAMESPACE, "-s", str(sig), data=b"probe", check=False)
    assert ok.returncode == 0, "this OpenSSH client cannot do `ssh-keygen -Y verify`: " + text


