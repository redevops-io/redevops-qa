@pytest.mark.parametrize("defect,exit_code", [("none", 0), ("discount", 1)])
def test_a_signed_bundle_verifies_with_the_supplied_key_and_exits_with_the_runs_own_status(tmp_path, defect, exit_code):
    files = golden(defect)
    path = archive(tmp_path, files)
    code, out, err = cli("anchor", "statement", path)                 # the first step of the two-step custody: print what to sign, take it to the machine that holds the key
    assert code == 0 and out.encode() == statement_for(files) and A.NAMESPACE in err
    priv, pub = keygen(tmp_path, "op")
    sig = sign_like_an_operator(priv, out.encode(), tmp_path)
    code, doc, _ = verify_json(path, "--anchor-sig", sig, "--anchor-pub", pub, "--require-signed-anchor")
    assert code == exit_code and doc["accepted"] is True and doc["assurance"] == "signed-anchor-verified" and doc["findings"] == []
    s = doc["anchor_signature"]
    assert s["state"] == "verified" and s["key_fingerprint"] == fingerprint_by_ssh_keygen(pub) and s["namespace"] == A.NAMESPACE
    assert s["statement"] == {"run_id": load(files, "report.json")["run_id"], "manifest_digest": manifest_digest(files), "plan_digest": load(files, "report.json")["plan_digest"]}
    assert doc["anchor"]["state"] == "absent"                          # the signature is not folded into the digest-comparison anchor
    text_code, text, _ = cli("verify", path, "--anchor-sig", sig, "--anchor-pub", pub)
    assert text_code == exit_code and "signed anchor: VERIFIED" in text and fingerprint_by_ssh_keygen(pub) in text
    assert A.TRUST_STATEMENT.format(run_id=s["statement"]["run_id"], plan_digest=s["statement"]["plan_digest"], fingerprint=s["key_fingerprint"]) in text
    for limit in ("does not show who holds that key", "that the key was not exposed", "when the signature was made", "uncompromised host", "application under test is correct"):
        assert limit in text
    assert "A bundle rewritten after signing would not verify." in text


def test_the_one_step_command_signs_with_the_operators_key_and_writes_the_signature_next_to_the_bundle(tmp_path, none_files):
    path = archive(tmp_path, none_files)
    priv, pub = keygen(tmp_path, "op")
    code, out, err = cli("anchor", "sign", path, "--key", priv)
    sig = Path(str(path) + ".anchor.sig")
    assert code == 0 and sig.read_text() == out and "BEGIN SSH SIGNATURE" in out and fingerprint_by_ssh_keygen(pub) in err and not (tmp_path / "bundle.tar.anchor.sig.pub").exists()
    code, doc, _ = verify_json(path, "--anchor-sig", sig, "--anchor-pub", pub, "--require-signed-anchor")
    assert code == 0 and doc["assurance"] == "signed-anchor-verified"


def test_the_one_step_command_can_sign_through_an_ssh_agent(tmp_path, none_files, monkeypatch):
    path = archive(tmp_path, none_files)
    priv, pub = keygen(tmp_path, "agentkey")
    sockdir = Path(tempfile.mkdtemp(prefix="qa-agent-", dir="/tmp"))
    sock = sockdir / "a.sock"
    agent = subprocess.Popen(["ssh-agent", "-D", "-a", str(sock)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        for _ in range(100):
            if sock.exists():
                break
            time.sleep(0.05)
        assert sock.exists()
        env = {**os.environ, "SSH_AUTH_SOCK": str(sock)}
        ssh("ssh-add", str(priv), env=env)
        os.chmod(priv, 0o000)                    # the private key cannot be read by anything but the agent now: signing must still work, which shows the tool is not reading it
        monkeypatch.setenv("SSH_AUTH_SOCK", str(sock))
        code, out, err = cli("anchor", "sign", path, "--key", pub, "--agent")
        assert code == 0, err
        os.chmod(priv, 0o600)
        code, doc, _ = verify_json(path, "--anchor-sig", str(path) + ".anchor.sig", "--anchor-pub", pub, "--require-signed-anchor")
        assert code == 0 and doc["anchor_signature"]["key_fingerprint"] == fingerprint_by_ssh_keygen(pub)
    finally:
        agent.terminate()
        agent.wait(timeout=10)
        os.chmod(priv, 0o600)
        shutil.rmtree(sockdir, ignore_errors=True)


