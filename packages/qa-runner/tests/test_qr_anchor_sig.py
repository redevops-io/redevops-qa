# ---- 4: the attack the feature exists for ----------------------------------------------------------------------------------------------------------------
@pytest.mark.parametrize("forge,run_exit", [(_drop_robot_lane, 0), (_weaken_the_assertion, 4), (_robot_reports_a_clean_run, 0)], ids=["failing-lane-dropped", "assertion-weakened", "robot-reports-a-clean-run"])
def test_a_bundle_rewritten_and_re_chained_after_signing_is_accepted_by_plain_verify_and_refused_by_the_signature(up, tmp_path, discount_files, forge, run_exit):
    """A tamperer with write access to the evidence rebuilds the whole bundle with this package's own builder: every digest, the manifest and the report agree. ``verify`` alone accepts it (the
    dropped lane and the engine's files rewritten to say the rule held: as VERIFIED; the last keeps the run id AND the plan digest, so only the manifest digest of the statement differs), and so does ``--require-anchor`` with the digest of the rewritten bundle itself. Only a digest or signature that was fixed BEFORE the rewrite refuses it."""
    genuine = archive(tmp_path, discount_files, "genuine.tar")
    priv, pub = keygen(tmp_path, "op")
    sig = sign_like_an_operator(priv, statement_for(discount_files), tmp_path)
    assert cli("verify", genuine, "--anchor-sig", sig, "--anchor-pub", pub, "--require-signed-anchor")[0] == 1          # the genuine run (FAILED, accepted) verifies as signed
    forged_files = forge(up, discount_files)
    assert manifest_digest(forged_files) != manifest_digest(discount_files)
    forged = archive(tmp_path, forged_files, "forged.tar")
    code, doc, _ = verify_json(forged)
    assert code == run_exit and doc["accepted"] is True and doc["findings"] == [] and doc["assurance"] == "internal-consistency-only"      # the rewrite passes (the dropped lane even as VERIFIED)
    code, doc, _ = verify_json(forged, "--anchor", manifest_digest(forged_files), "--require-anchor")
    assert code == run_exit and doc["assurance"] == "matches-supplied-anchor"                                                                      # even the digest check, with the digest of the rewrite
    code, doc, _ = verify_json(forged, "--anchor-sig", sig, "--anchor-pub", pub, "--require-signed-anchor")
    assert code == K.EXIT_REJECTED and doc["accepted"] is False and "ANCHOR_SIGNATURE_INVALID" in codes_of(doc) and doc["assurance"] == "rejected"
    assert doc["anchor_signature"]["state"] == "invalid" and doc["run_outcome"] is None
    text = cli("verify", forged, "--anchor-sig", sig, "--anchor-pub", pub)[1]
    assert "REJECTED" in text and "signed anchor: VERIFIED" not in text
    # the tamperer also hands the verifier the genuine digest as --anchor: the statement is still rebuilt from the bundle that is being verified
    from qa_runner.verify import verify_location
    v = verify_location(str(forged), anchor=manifest_digest(discount_files), anchor_sig=str(sig), anchor_pub=str(pub))
    assert v.signature.state == "invalid" and not v.accepted


# ---- 5: keys -------------------------------------------------------------------------------------------------------------------------------------------
def test_a_signature_by_one_key_does_not_verify_with_another_key_and_no_key_from_beside_the_signature_is_used(tmp_path, none_files):
    path = archive(tmp_path, none_files)
    priv1, pub1 = keygen(tmp_path, "one")
    priv2, pub2 = keygen(tmp_path, "two")
    sig = sign_like_an_operator(priv1, statement_for(none_files), tmp_path)
    for sibling in (Path(str(sig).replace(".sig", ".pub")), Path(str(sig) + ".pub"), Path(str(path) + ".pub")):
        shutil.copy(pub1, sibling)                                      # the signer's own public key travels with the signature and with the bundle
    code, doc, _ = verify_json(path, "--anchor-sig", sig, "--anchor-pub", pub2)
    assert code == K.EXIT_REJECTED and doc["anchor_signature"]["state"] == "invalid"
    assert cli("verify", path, "--anchor-sig", sig, "--anchor-pub", pub1)[0] == 0


def test_a_public_key_carried_by_the_bundle_is_never_consulted(tmp_path, up, none_files):
    """The key is in the report's extensions (the producer of the bundle can write anything there): without ``--anchor-pub`` it is a usage error, with another key it is refused."""
    from qr_tamper import forge_consistently
    priv, pub = keygen(tmp_path, "signer")
    _, other = keygen(tmp_path, "other")
    sig = sign_like_an_operator(priv, statement_for(none_files), tmp_path)
    carried = forge_consistently(up, none_files, edit_lane=lambda lid, o: o, extensions={"signer_public_key": pub.read_text().strip()})
    path = archive(tmp_path, carried)
    assert "signer_public_key" in load(carried, "report.json")["extensions"] and cli("verify", path)[0] == 0
    code, out, err = cli("verify", path, "--anchor-sig", sig)
    assert code == K.EXIT_USAGE and "--anchor-pub" in err
    # the statement of the bundle that carries the key is another one (its manifest differs), and the other key is not the signer's
    sig_carried = sign_like_an_operator(priv, statement_for(carried), tmp_path, name="carried")
    assert cli("verify", path, "--anchor-sig", sig_carried, "--anchor-pub", other)[0] == K.EXIT_REJECTED
    assert cli("verify", path, "--anchor-sig", sig_carried, "--anchor-pub", pub)[0] == 0


