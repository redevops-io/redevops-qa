def cli(*argv):
    out, err = io.StringIO(), io.StringIO()
    code = main([str(a) for a in argv], out, err)
    return code, out.getvalue(), err.getvalue()


# ---- real OpenSSH tools, real throwaway keys ----------------------------------------------------------------------------------------------------------
def ssh(*argv, data=None, check=True, cwd=None, env=None):
    done = subprocess.run(list(argv), input=data, capture_output=True, cwd=cwd, env=env, timeout=60)
    if check and done.returncode != 0:
        raise AssertionError(f"{argv[0]} {argv[1:3]} failed with {done.returncode}: {done.stderr.decode(errors='replace')[-200:]}")
    return done


def keygen(tmp_path, name, kind="ed25519"):
    """A throwaway key pair of the real ``ssh-keygen`` in its own 0700 directory; returns (private path, public path). The private key is 0600 and is only ever handed to ssh-keygen."""
    d = tmp_path / f"key-{name}"
    d.mkdir(mode=0o700)
    extra = ["-b", "2048"] if kind == "rsa" else []
    ssh("ssh-keygen", "-q", "-t", kind, *extra, "-N", "", "-C", "", "-f", str(d / "id"))
    assert stat.S_IMODE((d / "id").stat().st_mode) == 0o600
    return d / "id", d / "id.pub"


def fingerprint_by_ssh_keygen(pub) -> str:
    return ssh("ssh-keygen", "-l", "-f", str(pub)).stdout.decode().split()[1]


def sign_like_an_operator(key, statement: bytes, tmp_path, *, namespace=A.NAMESPACE, name="sig") -> Path:
    """What the printed instructions tell an operator to do: sign the statement bytes in a file with ``ssh-keygen -Y sign -n NAMESPACE -f KEY FILE`` (this writes FILE.sig)."""
    statement_file = tmp_path / f"{name}.statement"
    statement_file.write_bytes(statement)
    ssh("ssh-keygen", "-Y", "sign", "-n", namespace, "-f", str(key), str(statement_file))
    return Path(str(statement_file) + ".sig")


def statement_for(files) -> bytes:
    r = load(files, "report.json")
    return A.statement_bytes(r["run_id"], manifest_digest(files), r["plan_digest"])


def archive(tmp_path, files, name="bundle.tar") -> Path:
    path = tmp_path / name
    if path.exists():
        path.unlink()
    write_archive(dict(files), str(path))
    return path


def verify_json(path, *extra):
    code, out, err = cli("verify", path, "--json", *extra)
    return code, json.loads(out), err


def codes_of(doc):
    return sorted({f["code"] for f in doc["findings"]})


